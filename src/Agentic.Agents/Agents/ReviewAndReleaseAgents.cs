/// <summary>
/// Whole-codebase security/compliance review (defence in depth on top of per-change policy checks):
/// secrets, PII in logs, insecure constructs, dependency allowlist, plus a threat list from the design.
/// </summary>
public sealed partial class SecurityReviewerAgent : IAgent
{
    public string Name => "security-reviewer";

    [GeneratedRegex(@"<PackageReference\s+Include=""([^""]+)""\s+Version=""([^""]+)""")]
    private static partial Regex Package();

    public Task<AgentResult> ExecuteAsync(AgentContext ctx)
    {
        ctx.ReadText(WellKnownArtifacts.WorkspaceState);
        var design = ctx.Read<DesignSpec>(ArtifactKeys.Design);
        var files = ctx.Workspace.ListFiles()
            .Where(f => f.EndsWith(".cs") || f.EndsWith(".csproj") || f.EndsWith(".json"))
            .ToList();

        // Treat the whole tree as "added" so content policies inspect every line.
        var everything = new ChangeSet("full-scan", files.Select(f => new FileChange(f, ChangeKind.Create, ctx.Workspace.Read(f), "scan")).ToList());
        var scanners = PolicyEngine.Default().Policies.Where(p => p is SecretLeakPolicy or PiiLoggingPolicy or InsecureCodePolicy or DependencyAllowlistPolicy);
        var findings = new PolicyEngine(scanners)
            .Evaluate(new PolicySubject(ctx.Node, everything, _ => null))
            .Select(f => new SecurityFinding(f.PolicyId, f.Severity.ToString(), f.Path ?? "", f.Message))
            .ToList();

        var dependencies = files.Where(f => f.EndsWith(".csproj"))
            .SelectMany(f => Package().Matches(ctx.Workspace.Read(f)).Select(m => $"{m.Groups[1].Value} {m.Groups[2].Value} ({Path.GetFileName(f)})"))
            .ToList();
        var threats = (design?.Risks ?? []).Select(r => $"{r.Id}: {r.Description} → {r.Mitigation}").ToList();
        var blocking = findings.Any(f => f.Severity == nameof(PolicySeverity.Block));
        var report = new SecurityReport(findings, dependencies, threats, blocking);

        var result = blocking
            ? AgentResult.Permanent($"Blocking security findings: {string.Join("; ", findings.Where(f => f.Severity == "Block").Select(f => $"{f.Rule} {f.Path}"))}")
            : AgentResult.Success($"Scanned {files.Count} files: {findings.Count} findings (0 blocking); {dependencies.Count} dependencies on allowlist.");
        return Task.FromResult(result.WithJson(ArtifactKeys.SecurityReport, report));
    }
}

/// <summary>Generates API reference, design record and changelog from the approved design and spec.</summary>
public sealed class TechWriterAgent : IAgent
{
    public string Name => "tech-writer";

    public Task<AgentResult> ExecuteAsync(AgentContext ctx)
    {
        var spec = ctx.Require<RequirementSpec>(ArtifactKeys.RequirementSpec);
        var design = ctx.Require<DesignSpec>(ArtifactKeys.Design);
        var docs = new Dictionary<string, string>
        {
            ["docs/API.md"] = DocsRenderer.Api(spec, design),
            ["docs/DESIGN.md"] = DocsRenderer.Design(spec, design),
            ["CHANGELOG.md"] = DocsRenderer.Changelog(ctx, spec),
        };
        return Task.FromResult(DocsRenderer.Result(ctx, docs, "Full documentation set generated."));
    }
}

/// <summary>Fallback writer: minimal endpoint reference, flagged as documentation debt.</summary>
public sealed class MinimalDocsAgent : IAgent
{
    public string Name => "docs-minimal";

    public Task<AgentResult> ExecuteAsync(AgentContext ctx)
    {
        var spec = ctx.Require<RequirementSpec>(ArtifactKeys.RequirementSpec);
        var design = ctx.Require<DesignSpec>(ArtifactKeys.Design);
        var docs = new Dictionary<string, string> { ["docs/API.md"] = DocsRenderer.Api(spec, design) + "\n> Generated by the fallback writer; design notes and changelog are pending (documentation debt).\n" };
        return Task.FromResult(DocsRenderer.Result(ctx, docs, "Minimal API reference generated (fallback).")
            .WithDecision(DecisionCategory.Recovery, "Documentation debt recorded", "Primary documentation agent failed; minimal API reference keeps the release gate satisfiable, follow-up required."));
    }
}

internal static class DocsRenderer
{
    public static AgentResult Result(AgentContext ctx, Dictionary<string, string> docs, string summary)
    {
        var changes = docs
            .Where(d => !ctx.Workspace.Exists(d.Key) || ctx.Workspace.Read(d.Key) != d.Value)
            .Select(d => new FileChange(d.Key, ctx.Workspace.Exists(d.Key) ? ChangeKind.Modify : ChangeKind.Create, d.Value, "documentation"))
            .ToList();
        return AgentResult.Success(summary)
            .WithJson(ArtifactKeys.DocsManifest, new { files = docs.Keys, generatedBy = ctx.AgentName })
            .WithChanges(new ChangeSet("Documentation", changes));
    }

    public static string Api(RequirementSpec spec, DesignSpec design)
    {
        var sb = new StringBuilder($"# API reference — {spec.Title}\n\nErrors use RFC 7807 problem details (`application/problem+json`).\n\n| Method | Path | Summary | Request | Responses | Change |\n|---|---|---|---|---|---|\n");
        foreach (var e in design.Endpoints)
            sb.AppendLine($"| {e.Method} | `{e.Path}` | {e.Summary} | {e.Request ?? "—"} | {string.Join("<br>", e.Responses.Select(r => $"{r.Key} {r.Value}"))} | {e.Change ?? ""} |");
        return sb.ToString();
    }

    public static string Design(RequirementSpec spec, DesignSpec design)
    {
        var sb = new StringBuilder($"# Design — {spec.Title}\n\n{spec.ProblemStatement}\n\n{design.Summary}\n\n## Components\n\n");
        foreach (var c in design.Components)
            sb.AppendLine($"- **{c.Name}** — {c.Responsibility} (`{string.Join("`, `", c.Paths)}`)");
        sb.AppendLine("\n## Architecture decisions\n");
        foreach (var adr in design.Decisions)
            sb.AppendLine($"### {adr.Id}: {adr.Title}\n\n- Decision: {adr.Decision}\n- Rationale: {adr.Rationale}\n- Alternatives: {string.Join("; ", adr.Alternatives)}\n- Consequences: {adr.Consequences}\n");
        sb.AppendLine("## Risks\n\n| Id | Risk | Likelihood | Impact | Mitigation |\n|---|---|---|---|---|");
        foreach (var r in design.Risks)
            sb.AppendLine($"| {r.Id} | {r.Description} | {r.Likelihood} | {r.Impact} | {r.Mitigation} |");
        return sb.ToString();
    }

    public static string Changelog(AgentContext ctx, RequirementSpec spec)
    {
        var existing = ctx.Workspace.Exists("CHANGELOG.md") ? ctx.Workspace.Read("CHANGELOG.md") : "# Changelog\n";
        var version = ReleaseManagerAgent.NextVersion(ctx, spec);
        var notes = spec.Capabilities.Select(CapabilityCatalog.Get)
            .SelectMany(c => c.ReleaseNotes.Count > 0 ? c.ReleaseNotes : [$"Added: {c.Title}."]);
        var entry = $"\n## {version}\n\n{string.Join("\n", notes.Select(n => $"- {n}"))}\n";
        return existing.Contains($"## {version}\n") ? existing : existing.TrimEnd() + "\n" + entry;
    }
}

/// <summary>
/// Release readiness: evaluates the go/no-go checklist from upstream evidence, writes release notes
/// and a rollback plan. The node is high risk and always behind a human checkpoint.
/// </summary>
public sealed class ReleaseManagerAgent : IAgent
{
    public string Name => "release-manager";

    public Task<AgentResult> ExecuteAsync(AgentContext ctx)
    {
        var spec = ctx.Require<RequirementSpec>(ArtifactKeys.RequirementSpec);
        var plan = ctx.Require<WorkPlan>(ArtifactKeys.WorkPlan);
        var tests = ctx.Read<TestReport>(ArtifactKeys.TestReport);
        var trace = ctx.Read<List<TraceLink>>(ArtifactKeys.Traceability) ?? [];
        var security = ctx.Read<SecurityReport>(ArtifactKeys.SecurityReport);
        var docs = ctx.ReadText(ArtifactKeys.DocsManifest);
        var designApproved = ctx.Decisions.Any(d => d.NodeId == "design" && d.Category == DecisionCategory.Approval && d.Summary.StartsWith("Approved"));
        var policyBlocks = ctx.Decisions.Count(d => d.Category == DecisionCategory.Policy);

        var checklist = new List<ChecklistItem>
        {
            new("Test suite green", tests is { Failed: 0, Total: > 0 }, tests is null ? "no test report" : $"{tests.Passed}/{tests.Total} passed"),
            new("All acceptance criteria verified by passing tests", trace.Count > 0 && trace.All(t => t.Verified), $"{trace.Count(t => t.Verified)}/{trace.Count} verified"),
            new("No blocking security findings", security is { Blocking: false }, security is null ? "no security report" : $"{security.Findings.Count} findings, {security.Dependencies.Count} deps"),
            new("Documentation updated", docs is not null, docs is null ? "missing" : "docs manifest present"),
            new("Design approved by a human", designApproved, designApproved ? "approval recorded in decision log" : "no approval found"),
            new("Change control: no unresolved policy blocks", true, $"{policyBlocks} blocked proposals were rejected before apply"),
            new("Out-of-scope items logged as follow-ups", true, spec.OutOfScope.Count == 0 ? "none" : string.Join("; ", spec.OutOfScope)),
        };

        var version = NextVersion(ctx, spec);
        var rollback = new List<string>
        {
            "Redeploy the previous artifact (blue/green switch back); no data migration is involved (in-memory store).",
            "Source-level: revert the change sets listed in the audit log (engine keeps per-file compensation).",
        };
        if (spec.Capabilities.Contains("link-expiration"))
            rollback.Add("expiresAt is optional and additive; older clients are unaffected, so a rollback is safe.");
        if (spec.Capabilities.Any(c => c.StartsWith("rate-limit")))
            rollback.Add("Rate limits can be relaxed without deploy via RateLimiting:* configuration.");

        var readiness = new ReleaseReadiness(version, checklist.All(c => c.Passed), checklist, rollback,
            plan.Tasks.SelectMany(t => t.Files).Distinct().Order().ToList());
        var notes = $"# Release {version}\n\n{spec.ProblemStatement}\n\n"
            + string.Join("\n", spec.Capabilities.Select(CapabilityCatalog.Get).SelectMany(c => c.ReleaseNotes.Count > 0 ? c.ReleaseNotes : [$"Added: {c.Title}."]).Select(n => $"- {n}"))
            + (spec.OutOfScope.Count > 0 ? $"\n\n## Known follow-ups\n\n{string.Join("\n", spec.OutOfScope.Select(o => $"- {o}"))}" : "");

        var result = readiness.Ready
            ? AgentResult.Success($"Release {version} ready: {checklist.Count}/{checklist.Count} checks passed. Awaiting go/no-go.")
            : AgentResult.Permanent($"Release checklist failed: {string.Join("; ", checklist.Where(c => !c.Passed).Select(c => $"{c.Item} ({c.Evidence})"))}");
        return Task.FromResult(result.WithJson(ArtifactKeys.ReleaseReadiness, readiness).WithText(ArtifactKeys.ReleaseNotes, notes));
    }

    internal static string NextVersion(AgentContext ctx, RequirementSpec spec)
    {
        if (spec.IsGreenfield)
            return "1.0.0";
        var parts = (ctx.Setting(SettingKeys.BaselineVersion) ?? "1.0.0").Split('.').Select(int.Parse).ToArray();
        var kinds = spec.Capabilities.Select(c => CapabilityCatalog.Get(c).Kind).ToList();
        return kinds.Any(k => k == ChangeType.Enhancement) ? $"{parts[0]}.{parts[1] + 1}.0" : $"{parts[0]}.{parts[1]}.{parts[2] + 1}";
    }
}

/// <summary>
/// Fault injection for demonstrating recovery paths, configured per agent:
/// <c>agent:transient:N</c> fails the first N attempts of each execution; <c>agent:permanent</c> always fails.
/// </summary>
public sealed class FaultInjectingAgent(IAgent inner, string kind, int count) : IAgent
{
    public string Name => inner.Name;

    public Task<AgentResult> ExecuteAsync(AgentContext ctx) => kind switch
    {
        "transient" when ctx.Attempt <= count => Task.FromResult(AgentResult.Transient($"[fault-injection] simulated transient failure (attempt {ctx.Attempt}).")),
        "permanent" => Task.FromResult(AgentResult.Permanent("[fault-injection] simulated permanent failure (e.g. upstream model unavailable).")),
        _ => inner.ExecuteAsync(ctx),
    };

    public static IAgent Wrap(IAgent agent, string? faults)
    {
        foreach (var spec in (faults ?? "").Split(';', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
        {
            var parts = spec.Split(':');
            if (parts[0] == agent.Name)
                return new FaultInjectingAgent(agent, parts[1], parts.Length > 2 ? int.Parse(parts[2]) : 1);
        }
        return agent;
    }
}
